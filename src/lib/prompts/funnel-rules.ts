/**
 * Применяет funnel-rules блок к любому существующему системному промпту.
 * Вставляется после human-tone и после базовых бизнес-инструкций, но до
 * специфических правил длины/формата — воронка это mid-level рулинг.
 */
export function applyFunnelRules(baseStablePrompt: string): string {
  return `${baseStablePrompt}\n\n${FUNNEL_RULES_PROMPT}`;
}

/**
 * Короткий variable-часть напоминание об активной стадии воронки. Помогает
 * модели «не забыть» вести клиента вперёд на длинных диалогах.
 */
export function funnelStageHint(stageContext: {
  hasContact: boolean;
  hasIntent: boolean;
  turnCount: number;
}): string {
  if (stageContext.turnCount === 0) {
    return "[Стадия 1: приветствие. Не давай прайс сразу, задай 1 открытый вопрос.]";
  }
  if (!stageContext.hasIntent) {
    return "[Стадия 2: выясни потребность. 1 уточняющий вопрос, не больше.]";
  }
  if (stageContext.hasIntent && !stageContext.hasContact) {
    return "[Стадия 3-5: предложи решение и веди к записи/заказу. Не забудь попросить телефон перед create_booking/create_order.]";
  }
  return "[Стадия 6-7: закрывай запись/заказ, проговори детали. Возможна допродажа один раз.]";
}
