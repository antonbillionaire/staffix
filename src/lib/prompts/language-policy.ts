/**
 * Языковая политика бота — общая для режима услуг и режима продаж.
 *
 * ПОЧЕМУ ОБЩАЯ (17 сентября 2026). Подробная инструкция про язык жила только
 * в `ai-memory.ts`, то есть в промпте режима УСЛУГ. Магазинам, работающим по
 * `sales-prompt.ts`, доставалась одна строка «описания на языке клиента» —
 * без правила про узбекскую кириллицу, без дефолтного языка, без всего
 * остального. Асимметрия без причины: правило было написано, но половине
 * бизнесов не доезжало. У OLLEE узбекский текст есть в 339 ответах бота
 * из 1430, и качество там заметно хуже русского.
 *
 * ЧТО ДОБАВЛЕНО СВЕРХ ПЕРЕНЕСЁННОГО — по разбору реальных ответов бота:
 *
 *   «Менеджер сизга ВСКОРЕ хабар беради»   — русское слово посреди узбекской фразы
 *   «оформить қилмоқчисиз»                 — то же самое
 *   «ЖАҚШАН! 👍 Скриншотни юборинг»        — казахское слово в узбекском ответе
 *
 * Измерено: русские слова встречаются в 33 из 242 ответов узбекской латиницей,
 * казахские — в 3 ответах. Названия товаров из каталога в этот счёт входят
 * законно (правило «названия не переводим» действует и остаётся), речь только
 * про обычные слова.
 */

const LANG_LABEL: Record<string, string> = {
  ru: "русский",
  en: "английский",
  uz: "узбекский",
  kz: "казахский",
  kg: "киргизский",
  tj: "таджикский",
  am: "армянский",
  ge: "грузинский",
};

/**
 * Блок «Язык общения» для системного промпта.
 *
 * @param businessLanguage — `Business.language`; даёт ТОЛЬКО дефолт для
 *   сообщений, по которым язык не определить («ок», эмодзи). Жёсткой
 *   инструкции «отвечай на языке бизнеса» здесь нет и быть не должно:
 *   в сентябре 2026 такая инструкция заставляла Sonnet отвечать по-русски
 *   клиентам, писавшим на узбекском.
 */
export function buildLanguagePolicy(businessLanguage?: string | null): string {
  const defaultLang = LANG_LABEL[businessLanguage || ""] || "русский";
  return `Всегда отвечай на том же языке, на котором клиент написал ПОСЛЕДНЕЕ сообщение — русский, узбекский, казахский, английский. Определяй язык заново на каждое сообщение клиента. Дефолтный язык бизнеса — ${defaultLang}: используй его только если сообщение слишком короткое, чтобы определить язык (одно «ок», эмодзи, номер телефона).

ПИСЬМЕННОСТЬ. Узбекский бывает на латинице (sizga, rahmat, bog'lanamiz) и на кириллице (сизга, рахмат, боғланамиз). Отвечай ТОЙ ЖЕ письменностью, которой написал клиент — не переводи его с латиницы на кириллицу и наоборот. Узбекская кириллица использует буквы русского алфавита плюс ў, қ, ғ, ҳ — не путай её с русским языком.

НЕ СМЕШИВАЙ ЯЗЫКИ В ОДНОЙ ФРАЗЕ. Если отвечаешь на узбекском — все обычные слова узбекские. Русские слова вроде «вскоре», «оформить», «доставка», «скидка» внутри узбекской фразы — ошибка.

Исключение — НАЗВАНИЕ товара из каталога целиком: его пиши как в каталоге, чтобы клиент нашёл товар по этому названию. Но валюта и родовые слова вокруг названия — на языке ответа. По-узбекски: «so'm», а не «сум»; «yetkazib berish», а не «доставка»; «narxi», а не «цена».

УЗБЕКСКИЙ И КАЗАХСКИЙ — РАЗНЫЕ ЯЗЫКИ. «Жақсы», «рахмет», «сәлем» — казахские слова, в узбекском ответе их быть не должно. По-узбекски это «yaxshi», «rahmat», «salom».

НЕ ВЫДУМЫВАЙ СЛОВА. Если не уверен в узбекском или казахском слове — напиши русское название и короткое пояснение рядом. Русское слово в понятном месте лучше выдуманного: «Пенка (yuz uchun)» — нормально, «sudralgan suvdir» вместо мицеллярной воды — нет.`;
}
