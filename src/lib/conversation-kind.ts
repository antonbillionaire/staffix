/**
 * Тип входящего диалога (Этап 2.4 research-плана, 17 сентября 2026).
 *
 * Зачем: метрика «% диалогов, закрытых правильно» считается по диалогам
 * с покупателями. Если в знаменатель попадает входящая партнёрка, метрика
 * навсегда останется низкой и перестанет что-либо значить.
 *
 * Разметка 25 эскалаций OLLEE за 30 дней (Этап 0.2) дала такую картину:
 *   ~68 % — реальные клиенты с намерением купить
 *   ~20 % — блогеры, UGC-креаторы, предложения бартера
 *   ~12 % — прочее (эмодзи-реакции, дубли)
 *
 * То есть каждый пятый «потерянный клиент» в отчёте — это человек, который
 * вообще не собирался ничего покупать.
 *
 * Реализация намеренно простая — совпадение по словам, без модели:
 *   - не стоит денег и не добавляет латентности;
 *   - решение объяснимо: видно, какое слово сработало;
 *   - ошибку легко починить, дописав слово в список.
 * Классификатор на Haiku здесь был бы дороже и менее предсказуем при том,
 * что партнёрские запросы формулируются очень однообразно.
 */

export type ConversationKind =
  | "client" // покупатель — учитывается в метрике
  | "partnership" // блогер / UGC / бартер / реклама — в метрику не идёт
  | "unknown"; // сигналов не хватило

/**
 * Маркеры партнёрского обращения. Русский + узбекский: у OLLEE значимая
 * часть переписки идёт на узбекском, и такие запросы приходят на обоих.
 */
const PARTNERSHIP_MARKERS: readonly string[] = [
  // сотрудничество
  "сотрудничеств",
  "сотрудничать",
  "партнёрств",
  "партнерств",
  "бартер",
  "коллаборац",
  "collab",
  "hamkorlik", // сотрудничество (uz)
  // создатели контента
  "блогер",
  "блоггер",
  "инфлюенсер",
  "ugc",
  "креатор",
  "контент-мейкер",
  "контент мейкер",
  "обзор на ваш",
  "обзоры продукц",
  "рилс",
  "reels",
  "сторис за",
  "распаковк",
  "blogger",
  "kontent",
  // предложение услуг бренду
  "предлагаю сотруднич",
  "могу прорекламир",
  "прорекламирую",
  "реклама у меня",
  "мои подписчик",
  "моя аудитор",
  "подписчиков",
  "obunachi", // подписчики (uz)
  // входящие продажи нам
  "предлагаем услуги",
  "наша компания предлагает",
  "коммерческое предложение",
];

/** Маркеры покупателя — перевешивают партнёрские, если есть и те и другие. */
const CLIENT_MARKERS: readonly string[] = [
  "хочу заказать",
  "хочу купить",
  "оформить заказ",
  "сколько стоит",
  "какая цена",
  "есть в наличии",
  "доставка",
  "записаться",
  "запишите",
  "buyurtma", // заказ (uz)
  "narxi", // цена (uz)
  "sotib ol", // купить (uz)
  "yetkazib berish", // доставка (uz)
];

function countMarkers(text: string, markers: readonly string[]): number {
  let hits = 0;
  for (const m of markers) {
    if (text.includes(m)) hits++;
  }
  return hits;
}

/**
 * Классифицирует диалог по тексту сообщений КЛИЕНТА.
 *
 * Берутся только клиентские реплики: ответы бота содержат слова вроде
 * «доставка» и «цена» почти всегда и забили бы сигнал.
 *
 * @param clientMessages тексты сообщений клиента (роль "user")
 */
export function classifyConversationKind(clientMessages: readonly string[]): ConversationKind {
  if (clientMessages.length === 0) return "unknown";

  const text = clientMessages.join("\n").toLowerCase();
  const partnership = countMarkers(text, PARTNERSHIP_MARKERS);
  const client = countMarkers(text, CLIENT_MARKERS);

  // Любой явный покупательский маркер перевешивает партнёрские, сколько бы
  // их ни было. Два соображения:
  //
  //   1. Считать попадания и сравнивать числа нельзя: маркеры перекрываются
  //      («сотрудничеств» и «предлагаю сотруднич» дают два попадания на одной
  //      фразе), поэтому счёт меряет многословность, а не намерение.
  //   2. Ошибки здесь несимметричны. Блогер, который заодно решил купить, —
  //      это клиент, и потерять его из статистики хуже, чем засчитать лишний
  //      партнёрский диалог: метрика занизится, но реальная потеря не скроется.
  if (client > 0) return "client";
  if (partnership > 0) return "partnership";

  // Ни одного маркера — не гадаем. В метрику `unknown` идёт как клиент
  // (осторожная оценка: лучше занизить успех, чем скрыть потерю).
  return "unknown";
}

/** Учитывается ли диалог в метрике «% закрытых правильно». */
export function countsTowardFunnelMetric(kind: ConversationKind): boolean {
  return kind !== "partnership";
}
