/**
 * Регистрация новых аккаунтов закрыта (4 октября 2026).
 *
 * ЗАЧЕМ. Платформа остановлена целиком, пока решается, что делать с качеством
 * ответов ботов. Пускать в это время новых владельцев — значит отдавать им
 * продукт, который не работает: бот у них не ответит ни одному клиенту.
 *
 * Включается в Vercel: `STAFFIX_SIGNUP_CLOSED=1`. Любое другое значение или
 * отсутствие переменной — регистрация работает как обычно.
 *
 * Закрывается ТОЛЬКО создание новых аккаунтов. Вход существующих владельцев,
 * восстановление пароля и дашборд продолжают работать: у людей там свои
 * клиенты и своя переписка, запирать их снаружи нельзя.
 */
export function isSignupClosed(): boolean {
  return process.env.STAFFIX_SIGNUP_CLOSED === "1";
}

/** Текст для пользователя — один на API и на страницу, чтобы не разошлись. */
export const SIGNUP_CLOSED_MESSAGE =
  "Регистрация временно закрыта — мы дорабатываем сервис. Напишите нам, и мы сообщим, когда откроем.";
