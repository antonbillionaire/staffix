/**
 * Матчер имени файла к Product.sku для массовой загрузки фото товаров.
 *
 * Используется в /api/import/product-photos/commit — пользователь загружает
 * пачку картинок с именами вида `8809722156116.jpg` или `8809722156116_001.jpg`,
 * мы находим товар с соответствующим SKU (обычно штрихкод EAN-13) и
 * привязываем imageUrl.
 *
 * Логика "с суффиксом" появилась 12 августа 2026 после жалобы Farrukh
 * (OLLEE consultant): у него все файлы были `<штрихкод>_001.png`, а SKU
 * в каталоге — просто штрихкод без суффикса. Все 5 файлов уходили в
 * "не сматчено", он собирался вручную переименовывать сотни файлов.
 */

/** Убираем путь + расширение, оставляем только basename для сравнения с SKU. */
export function stripExt(filename: string): string {
  const parts = filename.split(/[\\/]/);
  const base = parts[parts.length - 1] || filename;
  const dotIdx = base.lastIndexOf(".");
  return (dotIdx > 0 ? base.slice(0, dotIdx) : base).trim();
}

/**
 * SKU-кандидаты для файла. Порядок = приоритет матчинга (первый найденный
 * в каталоге выигрывает). E-commerce photo-naming конвенция:
 *   8809.jpg              → ['8809']
 *   8809_001.jpg          → ['8809_001', '8809']       (главное фото товара)
 *   8809-2.jpg            → ['8809-2', '8809']
 *   8809 (1).jpg          → ['8809 (1)', '8809']
 *
 * Точное совпадение всегда важнее fallback'а — если у бизнеса реально
 * есть SKU `8809_001`, он выиграет; иначе снимем суффикс.
 *
 * Ограничение: суффикс должен быть 1-4 цифры. `88003_12345` (5 цифр) — это
 * скорее часть составного SKU, а не номер варианта фото; не стрипаем.
 */
export function candidateSkus(filename: string): string[] {
  const base = stripExt(filename);
  const out = [base];
  const m = base.match(/^(.+?)[\s_-]\(?(\d{1,4})\)?$/);
  if (m && m[1] && m[1] !== base) {
    out.push(m[1].trim());
  }
  return out;
}

/**
 * Приоритет фото при выборе главного (если несколько файлов матчатся к
 * одному товару). Чем меньше число — тем "главнее" фото:
 *   без суффикса → 0    (главное фото товара — 8809.jpg)
 *   с _001 → 1          (первое дополнительное — 8809_001.jpg)
 *   с _002 → 2 и т.д.
 *   не парсится → 0     (нет суффикса вообще)
 */
export function photoPriority(filename: string): number {
  const base = stripExt(filename);
  const m = base.match(/[\s_-]\(?(\d{1,4})\)?$/);
  if (!m) return 0;
  const n = parseInt(m[1], 10);
  return Number.isFinite(n) ? n : 0;
}
