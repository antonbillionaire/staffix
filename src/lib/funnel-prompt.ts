/**
 * Стадия и известные факты — в промпт (Шаг 4.3 + 4.4, 17 сентября 2026).
 *
 * До этого модель получала все 530 строк описания семи стадий и должна была
 * сама сообразить, на какой она сейчас. Теперь стадию знает код, и в промпт
 * идёт то, что нужно для ЭТОГО оборота: где мы, что уже выяснено, что уже
 * предлагали, куда двигаться дальше.
 *
 * Полное описание воронки из `funnel-rules.ts` остаётся на месте: там не только
 * стадии, но и правила поведения (не подгонять к покупке во время консультации,
 * не описывать фото которого не отправил, сравнивать товары по объективным
 * признакам). Этот блок его не заменяет, а снимает с модели работу по
 * угадыванию текущего шага.
 */

import {
  FUNNEL_STAGES,
  type FunnelStage,
  type FunnelKnownFacts,
} from "@/lib/funnel-state";

/** Сколько оборотов без движения считаем топтанием на месте. */
export const STUCK_AFTER_TURNS = 3;

/**
 * Что делать, когда разговор встал.
 *
 * Логика в коде, а не в промпте: правило «если клиент молчит — смени тактику»
 * модель соблюдает нестабильно, это уже проверено на телефоне и на эскалации.
 * Здесь мы не переписываем ответ бота, а меняем задачу, которую он решает —
 * вмешательство мягче, чем подмена текста, и уместнее: бот не соврал, он
 * просто ходит по кругу.
 */
export function buildStuckDirective(
  stage: FunnelStage,
  stageTurns: number,
  facts: FunnelKnownFacts
): string | null {
  if (stageTurns < STUCK_AFTER_TURNS) return null;

  const hasPhone = !!facts.phone?.trim();

  if (stage <= 2) {
    return "РАЗГОВОР СТОИТ НА МЕСТЕ. Хватит уточнять — предложи конкретный товар с ценой прямо сейчас, даже если картина неполная. Ещё один уточняющий вопрос клиент не выдержит.";
  }
  if (stage === 3 || stage === 4) {
    return "РАЗГОВОР СТОИТ НА МЕСТЕ. Хватит презентовать — задай прямой закрывающий вопрос: «Оформляем?» Если клиент уже отказался от предложенного, предложи ОДИН другой вариант и снова спроси.";
  }
  if (stage === 5) {
    return hasPhone
      ? "РАЗГОВОР СТОИТ НА МЕСТЕ. Телефон есть — не топчись, собирай остальные данные заказа одним сообщением и оформляй."
      : "РАЗГОВОР СТОИТ НА МЕСТЕ. Попроси номер телефона прямо и коротко, одной фразой, без повторной презентации товара.";
  }
  if (stage === 6) {
    return hasPhone
      ? "РАЗГОВОР СТОИТ НА МЕСТЕ. Все данные собраны — вызывай create_order, не переспрашивай."
      : "РАЗГОВОР СТОИТ НА МЕСТЕ. Клиент не даёт номер. Спроси один раз прямо; если снова не даст — вызови notify_manager и скажи, что менеджер ответит здесь же в чате.";
  }
  return "РАЗГОВОР СТОИТ НА МЕСТЕ. Заказ оформлен — заверши разговор коротко, ничего больше не предлагай.";
}

/**
 * Блок состояния для переменной части промпта.
 *
 * Идёт в variable-блок (TTL 5 минут), а не в stable: меняется каждый оборот и
 * в стабильном префиксе ломал бы кэш на 1 час.
 */
export function buildFunnelStateBlock(
  stage: FunnelStage,
  stageTurns: number,
  facts: FunnelKnownFacts
): string {
  const here = FUNNEL_STAGES[stage];
  const next = stage < 7 ? FUNNEL_STAGES[(stage + 1) as FunnelStage] : null;

  const lines: string[] = [
    `## ГДЕ ТЫ СЕЙЧАС В РАЗГОВОРЕ`,
    `Стадия ${stage} — ${here.name}. Цель сейчас: ${here.goal}.`,
  ];

  if (stage > 1) {
    lines.push(
      `Стадии 1-${stage - 1} пройдены: не здоровайся заново и не начинай разговор с начала.`
    );
  }
  if (next) {
    lines.push(`Следующая стадия — ${stage + 1} (${next.name}): ${next.goal}.`);
  }

  const known: string[] = [];
  if (facts.intent) known.push(`хочет: ${facts.intent}`);
  if (facts.forWhom) known.push(`для кого: ${facts.forWhom}`);
  if (facts.budget) known.push(`бюджет: ${facts.budget}`);
  if (facts.phone) {
    known.push(`телефон: ${facts.phone}`);
  }
  if (known.length > 0) {
    lines.push("", `УЖЕ ВЫЯСНЕНО — НЕ ПЕРЕСПРАШИВАЙ: ${known.join("; ")}.`);
  }

  if (facts.objections?.length) {
    lines.push(
      `КЛИЕНТ ВОЗРАЖАЛ: ${facts.objections.join("; ")}. Не делай вид, что этого не было.`
    );
  }
  if (facts.offered?.length) {
    lines.push(
      `УЖЕ ПРЕДЛАГАЛИ: ${facts.offered.join("; ")}. Не предлагай то же самое по второму кругу.`
    );
  }
  if (!facts.phone) {
    lines.push(
      "ТЕЛЕФОНА НЕТ. Без него нельзя ни оформить заказ, ни обещать звонок менеджера."
    );
  }

  // Модель сообщает о переходе, решает код — см. funnel-state.ts.
  lines.push(
    "",
    `Когда цель стадии достигнута — вызови advance_stage со следующим номером. Если клиент возразил, вызови advance_stage(4). Оставаться на стадии можно, для этого инструмент вызывать не нужно.`
  );

  const stuck = buildStuckDirective(stage, stageTurns, facts);
  if (stuck) lines.push("", `⚠️ ${stuck}`);

  return lines.join("\n");
}
