/**
 * Тесты для канонического списка stage-slug'ов (см. reenrich-catalog route).
 * Сам helper приватный в endpoint'е — здесь тестируем эквивалентную логику
 * чтобы зафиксировать правила «есть ли у товара функциональный тег».
 *
 * Если добавляешь новый stage-slug в endpoint — добавь и сюда, чтобы
 * закрепить регрессионным тестом.
 */
import { describe, it, expect } from "vitest";

// Дублируем словарь из endpoint (см. route.ts) для теста. Если endpoint
// обновляется, тесты должны сломаться до тех пор пока не синхронизируешь.
const STAGE_SLUGS = [
  "очищение",
  "умывание",
  "тонизация",
  "тонер",
  "эссенция",
  "сыворотка",
  "серум",
  "увлажнение",
  "уход",
  "крем для лица",
  "защита от солнца",
  "spf",
  "санскрин",
  "снятие макияжа",
  "демакияж",
  "маска для лица",
  "эксфолиация",
  "пилинг",
  "скраб",
  "патч",
  "макияж",
  "мейкап",
  "тональная основа",
  "bb-крем",
  "тушь для ресниц",
  "губная помада",
  "тени для век",
  "румяна",
  "уход за волосами",
  "шампунь",
  "кондиционер",
];

function hasStageTag(tags: string[]): boolean {
  if (!tags || tags.length === 0) return false;
  const lowered = new Set(tags.map((t) => t.trim().toLowerCase()));
  return STAGE_SLUGS.some((s) => lowered.has(s));
}

describe("hasStageTag", () => {
  it("Пустой массив → false", () => {
    expect(hasStageTag([])).toBe(false);
  });

  it("Массив без stage-тегов → false", () => {
    // Только бренд-теги
    expect(hasStageTag(["ollee", "оллее", "кор. косметика"])).toBe(false);
  });

  it("Есть тег «очищение» → true", () => {
    expect(hasStageTag(["пенка", "очищение", "лицо"])).toBe(true);
  });

  it("Case-insensitive: «SPF» матчит «spf»", () => {
    expect(hasStageTag(["солнце", "SPF"])).toBe(true);
  });

  it("Тег с пробелами по краям — тримится", () => {
    expect(hasStageTag(["  сыворотка  "])).toBe(true);
  });

  it("Частичное совпадение НЕ считается", () => {
    // "очистительный" содержит "очищ", но точное сравнение → false
    expect(hasStageTag(["очистительный"])).toBe(false);
  });

  it("Тональная основа как двусловный slug", () => {
    expect(hasStageTag(["макияж", "тональная основа"])).toBe(true);
  });

  it("BB-крем с дефисом", () => {
    expect(hasStageTag(["bb-крем"])).toBe(true);
    expect(hasStageTag(["BB-Крем"])).toBe(true);
  });

  it("Кириллический «крем» без «для лица» НЕ считается (слишком общий)", () => {
    // Целенаправленное решение: «крем» слишком общий термин, только
    // «крем для лица» / «bb-крем» / «крем для рук» и т.п. как stage.
    expect(hasStageTag(["крем", "лаванда"])).toBe(false);
  });

  it("Регресс: типовые OLLEE-товары должны распознаваться", () => {
    // Гидрофильное масло должно иметь «очищение» / «умывание»
    expect(hasStageTag(["гидрофильное", "масло", "очищение"])).toBe(true);
    // Мицеллярка
    expect(hasStageTag(["мицеллярная", "вода", "очищение", "демакияж"])).toBe(
      true
    );
    // BB-крем OLLEE
    expect(hasStageTag(["bb", "тонально", "spf", "матовый"])).toBe(true);
    // Энзимная пудра (та самая которую упоминала Ekaterina)
    expect(hasStageTag(["энзимная", "пудра", "очищение", "эксфолиация"])).toBe(
      true
    );
  });
});
