/**
 * Глобальный рубильник: Staffix не отвечает клиентам нигде (2 октября 2026).
 *
 * ЗАЧЕМ. У каждого бизнеса есть свой выключатель `Business.botActive`, и его
 * хватает, чтобы остановить ботов клиентов. Но у собственных ботов Staffix
 * (Виктор в Telegram, продающий бот в Instagram) выключателя не было вообще:
 * они привязаны не к Business, а к вебхукам платформы, и остановить их можно
 * было только снятием вебхука у Telegram.
 *
 * Переменная окружения действует на ВСЁ: и на ботов клиентов, и на боты
 * самого Staffix. Нужна на случай «остановить продукт целиком, пока
 * разбираемся» — именно так и появилась.
 *
 * Включается в Vercel: `STAFFIX_BOTS_PAUSED=1`. Любое другое значение или
 * отсутствие переменной — работа как обычно. Снимается удалением переменной.
 *
 * ВАЖНО: пауза останавливает ОТВЕТЫ, а не приём. Входящие сообщения клиентов
 * продолжают сохраняться в историю — владелец увидит их в дашборде и сможет
 * ответить вручную. Терять обращения клиентов нельзя даже на паузе.
 */
export function areBotsPaused(): boolean {
  return process.env.STAFFIX_BOTS_PAUSED === "1";
}
